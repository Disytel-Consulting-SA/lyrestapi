# Archivo generado con el mapping:
# tabla Libertya -> endpoint REST
ENDPOINTS_FILE="$TARGET_DIR/table-endpoints.properties"


# Funciones
generateSchemaModel() {
  if [ -z "$4" ]; then
    COLUMNAS="(lower(c.columnname))"
    FILTRO=" sin filtro de columnas"
  else
    COLUMNAS=$4
    FILTRO=" con filtro $4"
  fi
  echo "=== Generando schema $1 segun $2 en destino $TARGET_DIR/model/$3 $FILTRO ==="
  psql -h $HOST_NAME -p $HOST_PORT -U $USER_NAME -d $DB_NAME -Aqnt -f $QUERY_FILE -v nombre="'$1'" -v tabla="'$2'" -v columnas="$COLUMNAS" > $TARGET_DIR/model/"$3"
}

generateSchema() {
  ENTITY="$1"
  TABLE="$2"
  SCHEMA="$3"
  ENDPOINT="$4"
  COLUMNS="$5"

  generateSchemaModel "$ENTITY" "$TABLE" "$SCHEMA" "$COLUMNS"

  echo "$TABLE=/v1.0/$ENDPOINT" >> "$ENDPOINTS_FILE"
}


